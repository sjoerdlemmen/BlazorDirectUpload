using System.Security.Claims;
using Microsoft.AspNetCore.Http;

namespace DirectUpload.Server;

/// <summary>Configuration for the DirectUpload server endpoints.</summary>
public sealed class DirectUploadOptions
{
    /// <summary>Bucket that receives the uploads. Required.</summary>
    public string BucketName { get; set; } = "";

    /// <summary>
    /// Secret used to HMAC-sign upload tokens. Required, at least 32 bytes (UTF-8).
    /// Keep it out of source control; rotating it invalidates in-flight uploads.
    /// </summary>
    public string SigningKey { get; set; } = "";

    /// <summary>
    /// Preferred part size. Raised automatically to the S3 minimum (5 MiB) and,
    /// for very large files, to whatever keeps the upload within 10,000 parts.
    /// Default 16 MiB.
    /// </summary>
    public long PartSize { get; set; } = 16 * PartSizing.MiB;

    /// <summary>Largest accepted file in bytes. Default 50 GiB; hard ceiling is the S3 limit of 5 TiB.</summary>
    public long MaxFileSize { get; set; } = 50L * 1024 * PartSizing.MiB;

    /// <summary>Lifetime of each presigned part URL. Expired URLs are refreshed transparently. Default 1 hour.</summary>
    public TimeSpan UrlExpiry { get; set; } = TimeSpan.FromHours(1);

    /// <summary>How long an upload token stays valid, i.e. the longest an upload may take. Default 24 hours.</summary>
    public TimeSpan TokenLifetime { get; set; } = TimeSpan.FromHours(24);

    /// <summary>
    /// Prefix for object keys generated by the default <see cref="IUploadKeyPolicy"/>. Default <c>uploads/</c>.
    /// </summary>
    public string KeyPrefix { get; set; } = "uploads/";

    /// <summary>
    /// Content types accepted by the default <see cref="IUploadKeyPolicy"/>. Entries may end in <c>/*</c>
    /// (e.g. <c>video/*</c>). Empty means any content type.
    /// </summary>
    public IList<string> AllowedContentTypes { get; } = new List<string>();

    /// <summary>
    /// Resolves the id an upload token is bound to. Follow-up calls (part URLs, complete, abort) from a
    /// different user are rejected. Defaults to the NameIdentifier claim, then the identity name, then
    /// an empty string for anonymous users.
    /// </summary>
    public Func<HttpContext, string> UserIdResolver { get; set; } = DefaultUserId;

    private static string DefaultUserId(HttpContext context) =>
        context.User.FindFirstValue(ClaimTypes.NameIdentifier)
        ?? context.User.Identity?.Name
        ?? "";
}
